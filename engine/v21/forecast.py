def _importable(module: str) -> bool:
    try:
        importlib.import_module(module)
        return True
    except Exception:
        try:
            return os.path.isdir(os.path.join(os.getcwd(), module.replace(".", os.sep)))
        except Exception:
            return False


def status() -> List[Dict[str, Any]]:
    """Availability for every model, without importing heavy weights."""
    out = []
    for m in MODELS:
        entry = dict(m)
        if m["key"] == "kronos":
            try:
                from engine.kronos_service import get_kronos_service
                svc = get_kronos_service()
                st = svc.status()
                entry["available"] = bool(st.get("available") or st.get("loaded"))
                entry["detail"] = st
            except Exception as exc:  # noqa: BLE001
                entry["available"] = False
                entry["detail"] = {"error": str(exc)}
        else:
            entry["available"] = _importable(m["module"])
            entry["detail"] = {"hint": f"pip install -e <clone of {m['repo']}>"}
        out.append(entry)
    return out


def run(model_key: str, index: str = "NIFTY", horizon: int = 10) -> Dict[str, Any]:
    """
    Run exactly one model on the selected index's real bars.

    Returns ``available: False`` when the model is missing, so the panel can show
    the install command instead of an unrelated forecast.
    """
    key = idx.canonical(index)
    entry = next((m for m in MODELS if m["key"] == model_key), None)
    if entry is None:
        return {"available": False, "reason": f"unknown model {model_key}"}

    if model_key != "kronos":
        if not _importable(entry["module"]):
            return {"available": False, "model": entry["name"],
                    "reason": f"{entry['name']} is not installed. Clone {entry['repo']} "
                              f"and install it, then press run again."}
        return {"available": False, "model": entry["name"],
                "reason": f"{entry['name']} is importable but has no adapter in v2.1 yet; "
                          f"add one in engine/v21/forecast.py."}

    try:
        from engine.aite.exam import load_market_frame
        from engine.kronos_service import get_kronos_service
        import pandas as pd
        import numpy as np
    except Exception as exc:  # noqa: BLE001
        return {"available": False, "model": "KRONOS", "reason": str(exc)}

    df = load_market_frame(idx.aite_symbol(key), bars=400)
    if df is None or len(df) < 120:
        return {"available": False, "model": "KRONOS", "reason": "insufficient real bars"}

    svc = get_kronos_service()
    if not svc.available:
        return {"available": False, "model": "KRONOS",
                "reason": "KRONOS weights/torch not ready", "status": svc.status()}

    frame = df[["timestamps", "open", "high", "low", "close", "volume"]].tail(400).copy()
    frame["timestamps"] = pd.to_datetime(frame["timestamps"])
    x_ts = frame["timestamps"]
    last = x_ts.iloc[-1]
    freq = pd.infer_freq(x_ts) or "B"
    y_ts = pd.Series(pd.date_range(last, periods=horizon + 1, freq=freq)[1:])
    t0 = time.time()
    try:
        res = svc.forecast(frame, x_ts, y_ts, pred_len=horizon)
    except Exception as exc:  # noqa: BLE001
        return {"available": False, "model": "KRONOS", "reason": f"{type(exc).__name__}: {exc}"}

    preds = getattr(res, "predictions", None) or getattr(res, "forecast", None) or res
    closes = getattr(res, "close", None)
    try:
        values = np.asarray(closes if closes is not None else preds, dtype=float).ravel().tolist()
    except Exception:
        return {"available": False, "model": "KRONOS", "reason": "unexpected result shape"}

    return {
        "available": True,
        "model": "KRONOS",
        "index": key,
        "horizon": horizon,
        "seconds": round(time.time() - t0, 1),
        "values": [round(float(v), 2) for v in values[:horizon]],
        "timestamps": [str(t)[:10] for t in list(y_ts)[:horizon]],
        "last_close": round(float(frame["close"].iloc[-1]), 2),
        "chart": {"type": "forecast",
                  "history": [round(float(v), 2) for v in frame["close"].tail(60)],
                  "prediction": [round(float(v), 2) for v in values[:horizon]]},
        "note": "single model, single click — no ensemble, no blending",
    }
